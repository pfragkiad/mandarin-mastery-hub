#!/usr/bin/env python3
"""Tone pairs / Tone changes sidecar for the Pinyin sounds pages.

Reads the owner-supplied handoff under importer/data/tone-pairs/ (manifest.json is the
download manifest generated by the owner's prepare-tone-pairs-prototype.py) and writes the
small browser sidecar src/data/pinyin/tone-pairs.json, which the pages load lazily.

Fail-closed rules (nothing is inferred or repaired):
  * every pinned importer input must still match the manifest's SHA-256;
  * every example must be bound to an existing vocabulary record whose headword equals the
    example headword, whose reading equals the exact source reading (compared after NFC,
    case and space folding only, never tone marks) and whose audio attachment URL is the
    manifest's cdnUrl from the same Shtooka/Yue Tan source and licence;
  * every Sound chart link must be an attested syllable+tone in the pinyin inventory;
  * the 20 matrix cells (first tone 1-4 x second tone 1-4/neutral) hold exactly the
    ordinary examples; 一/不 rule examples stay outside the matrix.
Source readings, teaching labels and expected spoken drafts are copied as separate
fields; review status is kept as supplied (editorial draft, not listening-reviewed).

Usage: python3 scripts/import-tone-pairs.py --write
       python3 scripts/import-tone-pairs.py --check
       python3 scripts/import-tone-pairs.py --check --verify-cdn [--base http://localhost:8080]
         (--verify-cdn downloads each CDN recording and checks it is byte-identical to the
          pinned upstream MP3's SHA-256.)
"""
import sys as _sys
from pathlib import Path as _Path
_sys.path.insert(0, str(_Path(__file__).resolve().parent))
_sys.dont_write_bytecode = True
import vocabulary_store  # noqa: E402  (split-by-level vocabulary)
import argparse, hashlib, json, subprocess, sys, unicodedata

MANIFEST = 'importer/data/tone-pairs/manifest.json'
OUT = 'src/data/pinyin/tone-pairs.json'
# Inputs whose bytes are pinned by the manifest. The vocabulary/inventory hashes in the
# manifest describe the owner's snapshot; those files change with ordinary edits, so they
# are checked record by record below instead of by whole-file hash.
PINNED = ['importer/data/tone-pairs/examples.json', 'importer/data/tone-pairs/sources.json',
          'importer/data/tone-pairs/upstream-README.md', 'importer/data/tone-pairs/cc-by-sa-3.0-us-legalcode.html',
          'importer/data/hsk-audio/cmn-caen-tan-index.xml.bz2', 'importer/data/hsk-audio/cmn-caen-tan-readme.txt']
RULES = {'third', 'yi', 'bu'}

nfc = lambda s: unicodedata.normalize('NFC', s)
fold = lambda s: nfc(s).lower().replace(' ', '')
sha = lambda path: hashlib.sha256(open(path, 'rb').read()).hexdigest()

def fail(message):
    sys.exit(f'tone pairs: {message}')

def build():
    manifest = json.load(open(MANIFEST, encoding='utf-8'))
    if manifest.get('schemaVersion') != 'pinyin-tone-pairs-prototype/1': fail('unexpected manifest schema')
    for path in PINNED:
        if sha(path) != manifest['inputs'].get(path): fail(f'{path} does not match its pinned checksum')
    entries = {e['id']: e for e in vocabulary_store.read_vocabulary()['entries']}
    inventory = {s['base']: set(s['tones']) for s in json.load(open('src/data/pinyin/inventory.json', encoding='utf-8'))['syllables']}
    source = manifest['source']
    examples, ids = [], set()
    for row in manifest['examples']:
        hw = row['headword']
        if row['id'] in ids: fail(f'duplicate example id {row["id"]}')
        ids.add(row['id'])
        record = entries.get(row['vocabularyEntryId'] or '')
        if not record: fail(f'{hw}: vocabulary record {row["vocabularyEntryId"]} is missing')
        if nfc(record['simplified']) != nfc(hw): fail(f'{hw}: record headword is {record["simplified"]}')
        if fold(record['pinyinDisplay']) != fold(row['sourceReading']): fail(f'{hw}: record reading {record["pinyinDisplay"]} differs from source reading {row["sourceReading"]}')
        audio = record.get('audio') or {}
        if audio.get('url') != row['audio']['cdnUrl']: fail(f'{hw}: record recording is not the pinned CDN pointer')
        if 'Yue Tan' not in audio.get('source', '') or audio.get('license') != row['audio']['license']: fail(f'{hw}: record recording source/licence differs')
        tones = row['citationTones']
        if len(tones) != 2 or len(row['expectedSpokenTones']) != 2 or row['pair'] != f'{tones[0]}-{tones[1]}': fail(f'{hw}: pair/tones disagree')
        if row['rule'] is not None and row['rule'] not in RULES: fail(f'{hw}: unknown rule {row["rule"]}')
        if row['inPairMatrix'] == (row['rule'] in ('yi', 'bu')): fail(f'{hw}: 一/不 examples must stay outside the matrix (and only they)')
        if row['reviewStatus'] != manifest['reviewStatus']: fail(f'{hw}: review status differs')
        for link in row['chartLinks']:
            if link['tone'] not in inventory.get(link['base'], set()): fail(f'{hw}: {link["reading"]} is not an attested Sound chart sound')
        examples.append({
            'id': row['id'], 'sourceFileIds': row['sourceFileIds'], 'headword': hw, 'sourceReading': row['sourceReading'],
            'citationSyllables': row['citationSyllables'], 'citationTones': tones,
            'expectedSpokenSyllables': row['expectedSpokenSyllables'], 'expectedSpokenTones': row['expectedSpokenTones'],
            'pair': row['pair'], 'rule': row['rule'], 'inPairMatrix': row['inPairMatrix'], 'english': row['english'],
            'reviewStatus': row['reviewStatus'], 'vocabularyEntryId': row['vocabularyEntryId'],
            'chartLinks': [{'reading': l['reading'], 'base': l['base'], 'tone': l['tone']} for l in row['chartLinks']],
            'audio': {'url': row['audio']['cdnUrl'], 'upstreamUrl': row['audio']['upstreamUrl'], 'speaker': row['audio']['speaker'],
                      'source': audio['source'], 'license': row['audio']['license'], 'licenseUrl': row['audio']['licenseUrl'],
                      'recordingKind': row['audio']['recordingKind'], 'sha256': row['audio']['sha256']},
        })
    cells = {f'{a}-{b}': 0 for a in range(1, 5) for b in range(1, 6)}
    for e in examples:
        if e['inPairMatrix']:
            if e['pair'] not in cells: fail(f'{e["headword"]}: pair {e["pair"]} is outside the matrix')
            cells[e['pair']] += 1
    empty = [k for k, n in cells.items() if n == 0]
    if empty: fail(f'matrix cells without examples: {empty}')
    return {
        'schemaVersion': 'tone-pairs-sidecar/1',
        'generatedFrom': MANIFEST, 'acquiredOn': manifest['acquiredOn'], 'reviewStatus': manifest['reviewStatus'],
        'source': {k: source[k] for k in ('repository', 'commit', 'speaker', 'collection', 'copyright', 'license', 'licenseUrl', 'processingCredits')},
        'examples': examples,
    }

def verify_cdn(doc, base):
    for e in doc['examples']:
        data = subprocess.run(['curl', '-sSfL', base + e['audio']['url']], capture_output=True, check=True).stdout
        if hashlib.sha256(data).hexdigest() != e['audio']['sha256']: fail(f'{e["headword"]}: CDN recording differs from the pinned upstream MP3')
    print(f'{len(doc["examples"])} CDN recordings byte-identical to the pinned upstream MP3s')

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--write', action='store_true'); ap.add_argument('--check', action='store_true')
    ap.add_argument('--verify-cdn', action='store_true'); ap.add_argument('--base', default='http://localhost:8080')
    args = ap.parse_args()
    doc = build()
    text = json.dumps(doc, ensure_ascii=False, indent=1) + '\n'
    if args.write:
        open(OUT, 'w', encoding='utf-8').write(text)
        print(f'wrote {OUT}: {len(doc["examples"])} examples')
    elif args.check:
        if open(OUT, encoding='utf-8').read() != text: fail(f'{OUT} is out of date: run --write')
        print(f'{OUT} up to date: {len(doc["examples"])} examples')
    else:
        ap.error('choose --write or --check')
    if args.verify_cdn: verify_cdn(doc, args.base)

if __name__ == '__main__':
    main()
